#!/bin/sh
# 按坐标打字（H-048 真机验收）：用法 . scripts/type.sh && t "zhongguo"
# 坐标来自 2026-10-22 02:19 实测：qwerty 三行 cy 2090 / 2253 / 2420
# 底栏（H-054 后六个键）：九键79 ?123 231 中373 空格698 ⌫1033 ⏎1195，cy 2590
# 注意：H-054 加了「九键」后底栏整体左移，旧坐标 zh=262 会误点 ?123，勿再用。
K() { "$HDC" shell uitest uiInput click "$1" "$2" >/dev/null; sleep 0.35; }
t() {
  local s="$1"
  local i ch
  for ((i=0;i<${#s};i++)); do
    ch="${s:$i:1}"
    case "$ch" in
      q) K 63 2090;; w) K 191 2090;; e) K 319 2090;; r) K 447 2090;; t) K 575 2090;;
      y) K 703 2090;; u) K 831 2090;; i) K 959 2090;; o) K 1087 2090;; p) K 1215 2090;;
      a) K 114 2253;; s) K 245 2253;; d) K 377 2253;; f) K 508 2253;; g) K 639 2253;;
      h) K 771 2253;; j) K 902 2253;; k) K 1033 2253;; l) K 1165 2253;;
      z) K 248 2420;; x) K 378 2420;; c) K 509 2420;; v) K 640 2420;; b) K 770 2420;;
      n) K 901 2420;; m) K 1032 2420;;
      sp) K 698 2590;; bk) K 1033 2590;; ent) K 1195 2590;; q123) K 231 2590;; t9) K 79 2590;; zh) K 373 2590;;
      *) echo "unknown key: $ch";;
    esac
  done
}
